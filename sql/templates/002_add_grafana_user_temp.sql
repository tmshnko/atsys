CREATE USER IF NOT EXISTS ${GRAFANA_CH_USER}
IDENTIFIED WITH sha256_password BY '${GRAFANA_CH_PASSWORD}';

GRANT SELECT ON ${DB_NAME}.* TO ${GRAFANA_CH_USER};

CREATE SETTINGS PROFILE IF NOT EXISTS grafana_readonly
SETTINGS
    readonly = 1,
    max_execution_time CHANGEABLE_IN_READONLY
TO ${GRAFANA_CH_USER};